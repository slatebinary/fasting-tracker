'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/js/43k-stats-month-comparison-policy.js','utf8'),context={};
vm.createContext(context);vm.runInContext(source+'\nthis.select=selectStatsMonthComparisonPeriods;',context);
const select=context.select;
const months=Array.from({length:15},(_,i)=>({key:'month-'+i,hours:i*10}));
let result=select(months,'month-4');
assert.equal(result.index,4);
assert.equal(result.current,months[4]);
assert.equal(result.previous,months[3]);
assert.equal(result.yearAgo,undefined,'a selected month without twelve prior months has no year baseline');
result=select(months,'month-14');
assert.equal(result.index,14);
assert.equal(result.current,months[14]);
assert.equal(result.previous,months[13]);
assert.equal(result.yearAgo,months[2]);
result=select(months,'missing-key');
assert.equal(result.index,14,'an unmatched selection falls back to the latest month');
assert.equal(result.current,months[14]);
result=select(months,null);
assert.equal(result.index,14,'no selection falls back to the latest month');
const short=select([months[0]],null);
assert.equal(short.current,months[0]);
assert.equal(short.previous,undefined);
assert.equal(short.yearAgo,undefined);
assert.equal(select([],null),null);
assert.equal(select(null,null),null);
assert.equal(select({},null),null);
assert.equal(months.length,15,'the source array is not mutated');
console.log('PASS: Statistics month-comparison selection policy');
