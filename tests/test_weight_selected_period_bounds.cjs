'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/app/js/33f-weight-selected-period-bounds.js', 'utf8');
const context = {};
vm.runInNewContext(source + '\nthis.api = { resolveSelectedWeightPeriodBounds };', context, {filename:'33f-weight-selected-period-bounds.js'});
const resolve = context.api.resolveSelectedWeightPeriodBounds;
const bucket = (key, calendarDay, count=1, entry=null) => ({key,calendarDay,count,entry});
const fallback = mode => ({fallback:mode});
const common = {mode:'month',chartStyle:'rolling',todayCalendarDay:'2026-11-19',rollingWindowDays:mode=>({week:7,month:30,quarter:90,halfyear:180,year:365})[mode],fallbackBounds:fallback};
const selected = [bucket('2026-10','2026-10-01'),bucket('2026-11','2026-11-01')];
let result = resolve({...common,buckets:selected,selectedId:'2026-10'});
assert.equal(result.start.toISOString(),'2026-10-03T00:00:00.000Z');
assert.equal(result.end.toISOString(),'2026-11-01T23:59:59.999Z');
result = resolve({...common,buckets:selected,selectedId:'missing'});
assert.equal(result.end.toISOString(),'2026-11-01T23:59:59.999Z');
result = resolve({...common,buckets:[bucket('x','2026-11-19')],selectedId:'x',chartStyle:'fixed'});
assert.equal(result.start.toISOString(),'2026-11-01T00:00:00.000Z');
assert.equal(result.end.toISOString(),'2026-11-30T23:59:59.999Z');
result = resolve({...common,mode:'week',buckets:[bucket('w','2026-11-16')],selectedId:'w',chartStyle:'fixed'});
assert.equal(result.end.toISOString(),'2026-11-22T23:59:59.999Z');
result = resolve({...common,mode:'daily',buckets:[bucket('d',null,1,{when:'ignored'})],selectedId:'d',calendarDayForEntry:()=> '2026-11-05'});
assert.equal(result.start.toISOString(),'2026-10-07T00:00:00.000Z');
assert.equal(result.end.toISOString(),'2026-11-05T23:59:59.999Z');
result = resolve({...common,mode:'quarter',buckets:[],selectedId:null});
assert.equal(result.start.toISOString(),'2026-08-22T00:00:00.000Z');
assert.equal(result.end.toISOString(),'2026-11-19T23:59:59.999Z');
assert.deepEqual(resolve({...common,buckets:[],selectedId:null,todayCalendarDay:'bad'}),{fallback:'month'});
assert.deepEqual(resolve({...common,buckets:null,selectedId:null,todayCalendarDay:null}),{fallback:'month'});
console.log('PASS: selected Weight-period bounds, selected/latest fallback, fixed and rolling periods, daily entry dates and invalid-date fallback');
