'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/js/43g-weight-chart-hit-test-policy.js','utf8'),context={};
vm.createContext(context);vm.runInContext(source+'\nthis.api={nearestWeightChartPoint,nearestWeightChartPointAtX,isWeightChartPointerTap};',context);
const {nearestWeightChartPoint:nearest,nearestWeightChartPointAtX:nearestX,isWeightChartPointerTap:isTap}=context.api;
const points=[{id:'a',x:0,y:0},{id:'b',x:10,y:10},{id:'c',x:20,y:0}];
assert.equal(nearest(points,9,9),points[1]);
assert.equal(nearest([{id:'edge',x:0,y:0}],28,0).id,'edge');
assert.equal(nearest([{id:'outside',x:0,y:0}],28.01,0),null);
assert.equal(nearest(points,0,29),null);
assert.equal(nearest([],0,0),null);
assert.equal(nearest(null,0,0),null);
assert.equal(nearest(points,5,5),points[0],'equal-distance ties retain the first point');
assert.equal(nearestX(points,13,3),points[1]);
assert.equal(nearestX(points,13,2.99),null);
assert.equal(nearestX([],0,10),null);
assert.equal(nearestX(points,5,5),points[0],'horizontal ties retain the first point');
assert.equal(isTap(0,0,10,0,0,8),true);
assert.equal(isTap(0,0,10.001,0,0,0),false);
assert.equal(isTap(0,0,0,10.001,0,0),false);
assert.equal(isTap(0,0,0,0,0,8.001),false);
assert.equal(isTap(0,0,0,0,8,0),true);
assert.equal(isTap(0,0,0,0,0,0),true);
assert.deepEqual(points.map(p=>[p.id,p.x,p.y]),[['a',0,0],['b',10,10],['c',20,0]]);
console.log('PASS: Weight chart nearest-point selection, hit tolerances and pointer tap thresholds');
