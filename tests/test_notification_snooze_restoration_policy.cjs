'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/js/43q-notification-snooze-restoration-policy.js','utf8');
const context={};vm.createContext(context);vm.runInContext(source+'\nthis.resolve=resolveDueSnoozedNotificationDetailsPolicy;',context);
const resolve=context.resolve;
const now=Date.parse('2026-11-20T12:00:00.000Z'), screens=['fasting','history','weight','stats','settings'];
const parse=value=>{const date=new Date(value);return Number.isFinite(date.getTime())?date:null;};
const item=(id,until,extra={})=>({id,kind:'target',screen:'stats',snoozedUntil:until,params:{targetHours:18},...extra});
const due=item('due',new Date(now).toISOString());
const future=item('future',new Date(now+60000).toISOString());
const expiredInvalid=item('invalid','not-a-date');
const missing=item('',new Date(now-1000).toISOString());
const duplicate=item('already-active',new Date(now-1000).toISOString());
const active=[{id:'already-active',kind:'backup',screen:'settings',createdAt:new Date(now-5000).toISOString(),params:{}}];
const pending=[due,future,expiredInvalid,missing,duplicate,null,'bad'];
const original=JSON.stringify(pending), activeOriginal=JSON.stringify(active);
const result=resolve(pending,active,now,parse,screens,10);
assert.deepEqual(JSON.parse(JSON.stringify(result.due)),[due,duplicate]);
assert.deepEqual(JSON.parse(JSON.stringify(result.remaining)),[future]);
assert.equal(result.restored.length,1,'already-active IDs must not be restored twice');
assert.equal(result.restored[0].id,'due');
assert.equal(result.restored[0].createdAt,new Date(now).toISOString());
assert.deepEqual(JSON.parse(JSON.stringify(result.details)).map(x=>x.id),['due','already-active']);
assert.equal(JSON.stringify(pending),original,'policy must not mutate pending data');
assert.equal(JSON.stringify(active),activeOriginal,'policy must not mutate active data');
const invalidScreen=resolve([item('screen',new Date(now-1).toISOString(),{screen:'unknown',params:[]})],[],now,parse,screens,5);
assert.equal(invalidScreen.restored[0].screen,'fasting');
assert.deepEqual(JSON.parse(JSON.stringify(invalidScreen.restored[0].params)),[],'preserve the existing object-type params acceptance');
assert.equal(resolve([],[],now,parse,screens,5).due.length,0);
const capped=resolve([item('a',new Date(now-1).toISOString()),item('b',new Date(now-1).toISOString())],[],now,parse,screens,1);
assert.deepEqual(capped.details.map(x=>x.id),['b']);
console.log('PASS: snoozed notification restoration covers due/future/invalid records, duplicate suppression, ordering, limits and immutability');
