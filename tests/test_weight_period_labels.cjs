'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/app/js/33g-weight-period-labels.js', 'utf8');
const context = {};
vm.runInNewContext(source + '\nthis.api = { resolveWeightBucketLabel };', context, {filename:'33g-weight-period-labels.js'});
const resolve = context.api.resolveWeightBucketLabel;
const bucketDate = key => {
  const match = /^(\\d{4})-(\\d{2})-(\\d{2})$/.exec(String(key || ''));
  if (!match) return new Date(NaN);
  const [year,month,day] = match.slice(1).map(Number);
  return new Date(Date.UTC(year,month-1,day,12));
};
const translations = (key,values) => key + ':' + Object.entries(values).map(([name,value])=>name+'='+value).join(',');
const common = {locale:'en-GB',timeZone:'UTC',bucketDate,translate:translations,localDateTimeLabel:(when,tz)=>'LOCAL:'+when+':'+(tz||'')};
const day = {when:'2026-11-05T13:45:00.000Z',timeZone:'Europe/Sofia'};
const daily = {key:'entry:1',entry:day};
assert.equal(resolve({...common,bucket:daily,mode:'daily',variant:'long'}),'LOCAL:2026-11-05T13:45:00.000Z:Europe/Sofia');
assert.equal(resolve({...common,bucket:daily,mode:'daily',variant:'short'}),new Date(day.when).toLocaleDateString('en-GB',{day:'numeric',month:'short',year:'2-digit',timeZone:'Europe/Sofia'}));
assert.equal(resolve({...common,bucket:daily,mode:'daily',variant:'callout'}),new Date(day.when).toLocaleString('en-GB',{day:'numeric',month:'short',hour:'2-digit',minute:'2-digit',timeZone:'Europe/Sofia'}));
const week = {key:'2026-11-16'};
assert.equal(resolve({...common,bucket:week,mode:'week',variant:'long'}),'weight.weekOf:date='+bucketDate(week.key).toLocaleDateString('en-GB',{day:'numeric',month:'short',year:'numeric',timeZone:'UTC'}));
assert.equal(resolve({...common,bucket:week,mode:'week',variant:'short'}),bucketDate(week.key).toLocaleDateString('en-GB',{day:'numeric',month:'short',timeZone:'UTC'}));
const month = {key:'2026-11-01'};
assert.equal(resolve({...common,bucket:month,mode:'month',variant:'long'}),bucketDate(month.key).toLocaleDateString('en-GB',{month:'long',year:'numeric',timeZone:'UTC'}));
assert.equal(resolve({...common,bucket:month,mode:'month',variant:'short'}),bucketDate(month.key).toLocaleDateString('en-GB',{month:'short',year:'2-digit',timeZone:'UTC'}));
assert.equal(resolve({...common,bucket:{key:'2026-10-01'},mode:'quarter',variant:'long'}),'weight.quarterLabel:quarter=4,year=2026');
assert.equal(resolve({...common,bucket:{key:'2026-10-01'},mode:'quarter',variant:'short'}),'weight.quarterShort:quarter=4,year=26');
assert.equal(resolve({...common,bucket:{key:'2026-07-01'},mode:'halfyear',variant:'long'}),'weight.halfYearLabel:half=2,year=2026');
assert.equal(resolve({...common,bucket:{key:'2026-07-01'},mode:'halfyear',variant:'short'}),'weight.halfYearShort:half=2,year=26');
assert.equal(resolve({...common,bucket:{key:'2026-01-01'},mode:'year',variant:'long'}),'2026');
assert.equal(resolve({...common,bucket:{key:'2026-01-01'},mode:'year',variant:'short'}),'2026');
const rolling = {calendarDay:'2026-11-19',windowStartDay:'2026-11-13',windowEndDay:'2026-11-19',rollingWindowDays:7};
assert.equal(resolve({...common,bucket:rolling,mode:'week',variant:'long'}),bucketDate('2026-11-13').toLocaleDateString('en-GB',{day:'numeric',month:'short',year:'numeric',timeZone:'UTC'})+' – '+bucketDate('2026-11-19').toLocaleDateString('en-GB',{day:'numeric',month:'short',year:'numeric',timeZone:'UTC'}));
assert.equal(resolve({...common,bucket:rolling,mode:'week',variant:'short'}),bucketDate('2026-11-19').toLocaleDateString('en-GB',{day:'numeric',month:'short',timeZone:'UTC'}));
assert.equal(resolve({...common,bucket:week,mode:'week',variant:'callout'}),resolve({...common,bucket:week,mode:'week',variant:'long'}));
assert.equal(resolve({...common,bucket:null,mode:'week',variant:'long'}),'');
assert.equal(resolve({...common,bucket:week,mode:'week',variant:'unknown'}),'');
console.log('PASS: Weight bucket long, short and callout labels across Daily, Week, Month, Quarter, Half-year, Year and rolling windows');
