'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/js/43i-stats-chart-marker-density.js','utf8'),context={};
vm.createContext(context);vm.runInContext(source+'\nthis.step=statsChartMarkerStep;',context);
const step=context.step;
for(let n=0;n<=31;n++)assert.equal(step(n,1,'all'),1,`dense markers remain complete through ${n} points`);
assert.equal(step(32,660,'30d'),1);
assert.equal(step(1000,600,'30d'),25);
assert.equal(step(1000,600,'6m'),30);
assert.equal(step(1000,600,'1y'),38);
assert.equal(step(1000,600,'all'),48);
assert.equal(step(1000,1,'30d'),500,'at least two marker slots are retained on narrow plots');
assert.equal(step(1000,0,'30d'),500,'zero width is normalized to one pixel');
assert.equal(step(-5,600,'30d'),1);
assert.equal(step('not-a-number',600,'30d'),1);
assert.equal(step(1000,600,'unknown'),25,'unknown ranges retain the default spacing');
console.log('PASS: Statistics chart marker density across point counts, widths and ranges');
