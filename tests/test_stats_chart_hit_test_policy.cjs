'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/js/43h-stats-chart-hit-test-policy.js','utf8'),context={};
vm.createContext(context);vm.runInContext(source+'\nthis.hit=nearestStatsChartDayHit;',context);
const hit=context.hit,bounds={left:10,right:110,top:20,bottom:220};
const points=[{id:'first',x:20},{id:'middle',x:60},{id:'last',x:90}];
assert.equal(hit(58,100,bounds,points),points[1]);
assert.equal(hit(40,100,bounds,points),points[0],'equal-distance ties retain the first point');
assert.equal(hit(bounds.left-12,100,bounds,points),points[0],'left horizontal tolerance is inclusive');
assert.equal(hit(bounds.right+12,100,bounds,points),points[2],'right horizontal tolerance is inclusive');
assert.equal(hit(60,bounds.top-24,bounds,points),points[1],'top vertical tolerance is inclusive');
assert.equal(hit(60,bounds.bottom+24,bounds,points),points[1],'bottom vertical tolerance is inclusive');
assert.equal(hit(bounds.left-12.001,100,bounds,points),null);
assert.equal(hit(bounds.right+12.001,100,bounds,points),null);
assert.equal(hit(60,bounds.top-24.001,bounds,points),null);
assert.equal(hit(60,bounds.bottom+24.001,bounds,points),null);
assert.equal(hit(60,100,null,points),null);
assert.equal(hit(60,100,bounds,[]),null);
assert.equal(hit(60,100,bounds,null),null);
assert.equal(hit(60,100,bounds,undefined),null);
assert.deepEqual(points.map(p=>[p.id,p.x]),[['first',20],['middle',60],['last',90]],'hit testing does not mutate chart geometry');
console.log('PASS: Statistics Trend and Cumulative chart hit-testing boundaries, nearest-day selection and tie resolution');
