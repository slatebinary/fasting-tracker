const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/app/js/43z-post-start-extension-policy.js', 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(source + '\nthis.api={POST_START_EXTENSION_GRACE_MS,POST_START_EXTENSION_MINUTES,resolvePostStartExtensionWindow,resolvePostStartExtendedTimestamp};', context);
const p = context.api;
const now = Date.parse('2026-11-21T12:30:00.000Z');
const created = new Date(now - 10 * 60000).toISOString();
assert.equal(p.POST_START_EXTENSION_GRACE_MS, 30 * 60000);
assert.deepEqual(Array.from(p.POST_START_EXTENSION_MINUTES), [5,10,15,30]);
assert.deepEqual({...p.resolvePostStartExtensionWindow(created, now)}, {eligible:true, remainingMs:20*60000});
assert.deepEqual({...p.resolvePostStartExtensionWindow(new Date(now-30*60000).toISOString(), now)}, {eligible:false, remainingMs:0});
assert.deepEqual({...p.resolvePostStartExtensionWindow(new Date(now-30*60000+1).toISOString(), now)}, {eligible:true, remainingMs:1});
assert.deepEqual({...p.resolvePostStartExtensionWindow(new Date(now+60001).toISOString(), now)}, {eligible:false, remainingMs:0});
assert.deepEqual({...p.resolvePostStartExtensionWindow('not-a-date', now)}, {eligible:false, remainingMs:0});
assert.deepEqual({...p.resolvePostStartExtensionWindow(created, NaN)}, {eligible:false, remainingMs:0});
const start = new Date(now-3*60000).toISOString();
assert.equal(p.resolvePostStartExtendedTimestamp(start, 5), now+2*60000);
assert.equal(p.resolvePostStartExtendedTimestamp(start, 30), now+27*60000);
for (const invalid of [0,1,4,6,20,60,'15x',null]) assert.equal(p.resolvePostStartExtendedTimestamp(start, invalid), null);
assert.equal(p.resolvePostStartExtendedTimestamp('bad-date', 5), null);
console.log('PASS: post-start non-fasting extension grace window, allowlist and timestamp arithmetic');
